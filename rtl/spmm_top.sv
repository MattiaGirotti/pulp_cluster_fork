
// ============================================================================
// Module: spmm_top
// Description: Top-level CSR SpMM accelerator for PULP cluster.
//              Control path:
//              HWPE target -> spmm_target_decoder -> streamer -> scheduler
// ============================================================================

import hci_package::*;
import hwpe_ctrl_package::*;
import spmm_pkg::*;

module spmm_top #(
    parameter int unsigned DATA_WIDTH      = 8,
    parameter int unsigned NUM_MACS        = 16,
    parameter int unsigned NUM_ROWS        = 16,
    parameter int unsigned TOTAL_NNZ       = 64,
    parameter int unsigned TOTAL_PTRS      = 17,
    parameter int unsigned STREAM_WORD_BIT = 128,
    parameter int unsigned DATA_WIDTH_OUT  = 8,
    parameter bit          USE_LATCHES     = 0,
    parameter int unsigned N_CORES         = 8,

    // HCI parameters inherited from the cluster HWPE port
    parameter int unsigned HCI_DW          = 288,
    parameter int unsigned HCI_AW          = 32,
    parameter int unsigned HCI_EW          = 72,
    parameter int unsigned HCI_EHW         = 1
)(
    input  logic                         clk_i,
    input  logic                         rst_ni,

    output logic [N_CORES-1:0][1:0]       evt_o,
    output logic                         busy_o,

    // TCDM Master Interface
    hci_core_intf.initiator              tcdm_master,

    // HWPE Controller Target Interface
    hwpe_ctrl_intf_periph.slave          target
);

    // ========================================================================
    // 0. CONTROL SIGNALS
    // ========================================================================

    spmm_config_t accel_config;

    logic accel_config_valid;
    logic target_clear;

    // Streamer control
    logic streamer_start;
    logic streamer_done;

    // Scheduler control
    logic accel_start;
    logic accel_done;

    // ------------------------------------------------------------------------
    // Decoder output:
    // config_valid_o = job_trigger (generated by hwpe_ctrl_target)
    //
    // IMPORTANT:
    // streamer_start is a one-cycle trigger, not a level derived from busy.
    // ------------------------------------------------------------------------

    assign streamer_start = accel_config_valid;


    // ========================================================================
    // 1. HCI INTERFACE AND ECC
    // ========================================================================

    localparam hci_size_parameter_t SPMM_HCI_SIZE = '{
        DW:  HCI_DW,
        AW:  HCI_AW,
        BW:  8,
        UW:  1,
        IW:  8,
        EW:  HCI_EW,
        EHW: HCI_EHW,
        FD:  0
    };

    hci_core_intf #(
        .DW  (HCI_DW),
        .AW  (HCI_AW),
        .BW  (8),
        .UW  (1),
        .IW  (8),
        .EW  (HCI_EW),
        .EHW (HCI_EHW)
    ) tcdm_master_raw (
        .clk(clk_i)
    );

    hci_ecc_enc #(
        .ENABLE_DATA             (1'b0),
        .HCI_SIZE_tcdm_target    (SPMM_HCI_SIZE),
        .HCI_SIZE_tcdm_initiator (SPMM_HCI_SIZE)
    ) i_spmm_hci_ecc_enc (
        .r_data_single_err_o     (),
        .r_data_multi_err_o      (),
        .r_meta_single_err_o     (),
        .r_meta_multi_err_o      (),
        .tcdm_target             (tcdm_master_raw),
        .tcdm_initiator          (tcdm_master)
    );


    // ========================================================================
    // 2. HWPE TARGET DECODER
    // ========================================================================

    spmm_target_decoder #(
        .OpIdWidth (4)
    ) i_spmm_target_decoder (
        .clk_i            (clk_i),
        .rst_ni           (rst_ni),

        .target_clear_o   (target_clear),

        // A new configuration can be accepted only when streamer is idle.
        .config_ready_i   (~busy_o),

        // The current operation is complete when the streamer finishes.
        .op_done_i        (streamer_done),

        .config_valid_o   (accel_config_valid),
        .config_o         (accel_config),

        .target           (target)
    );


    // ========================================================================
    // 3. STREAMER <-> INPUT BUFFERS INTERFACE
    // ========================================================================

    logic                       a_write_en;
    logic [STREAM_WORD_BIT-1:0] a_wdata;

    logic                       b_write_en;
    logic [STREAM_WORD_BIT-1:0] b_wdata;

    logic                       col_id_write_en;
    logic [STREAM_WORD_BIT-1:0] col_id_wdata;

    logic                       row_ptr_write_en;
    logic [STREAM_WORD_BIT-1:0] row_ptr_wdata;


    // ========================================================================
    // 4. C BUFFER READ INTERFACE
    // ========================================================================

    logic [$clog2(NUM_ROWS)-1:0] c_read_row_addr;

    logic [$clog2((NUM_MACS * DATA_WIDTH_OUT) /
                  STREAM_WORD_BIT)-1:0] c_read_word_addr;

    logic [STREAM_WORD_BIT-1:0] c_rdata;


    // ========================================================================
    // 5. ROW POINTER BUFFER <-> SCHEDULER
    // ========================================================================

    logic [$clog2(TOTAL_PTRS-1)-1:0] row_ptr_read_addr;

    logic [DATA_WIDTH-1:0] row_ptr_start;
    logic [DATA_WIDTH-1:0] row_ptr_end;


    // ========================================================================
    // 6. COLUMN ID BUFFER <-> SCHEDULER
    // ========================================================================

    logic [$clog2(TOTAL_NNZ)-1:0] col_id_read_addr;

    logic [DATA_WIDTH-1:0] col_id_data;


    // ========================================================================
    // 7. A BUFFER <-> SCHEDULER / DATAPATH
    // ========================================================================

    logic [$clog2(TOTAL_NNZ)-1:0] a_read_addr;

    logic unsigned [DATA_WIDTH-1:0] a_data;


    // ========================================================================
    // 8. B BUFFER <-> SCHEDULER / DATAPATH
    // ========================================================================

    logic [$clog2(NUM_ROWS)-1:0] b_read_row_addr;

    logic unsigned [NUM_MACS-1:0][DATA_WIDTH-1:0] b_data;


    // ========================================================================
    // 9. C BUFFER <-> DATAPATH
    // ========================================================================

    logic c_buf_write_en;

    logic [$clog2(NUM_ROWS)-1:0] c_buf_write_row_addr;


    // ========================================================================
    // 10. SCHEDULER <-> DATAPATH
    // ========================================================================

    logic dp_in_valid;
    logic dp_in_ready;

    logic [DATA_WIDTH-1:0] dp_nnz_iterations;

    logic dp_out_valid;
    logic dp_out_ready;

    logic unsigned [NUM_MACS-1:0][DATA_WIDTH_OUT-1:0] dp_data_out;

    logic dp_matrix_end;


    // ========================================================================
    // 11. STREAMER
    // ========================================================================

    streamer #(
        .DATA_WIDTH      (DATA_WIDTH),
        .NUM_MACS        (NUM_MACS),
        .NUM_ROWS        (NUM_ROWS),
        .TOTAL_NNZ       (TOTAL_NNZ),
        .TOTAL_PTRS      (TOTAL_PTRS),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .DATA_WIDTH_OUT  (DATA_WIDTH_OUT)
    ) i_spmm_streamer (

        .clk_i               (clk_i),
        .rst_ni              (rst_ni),

        // Clear generated by HWPE target
        .clear_i             (target_clear),

        // Start generated by HWPE target decoder
        .start_i             (streamer_start),

        .busy_o              (busy_o),
        .done_o              (streamer_done),

        // Configuration registers
        .a_base_addr_i       (accel_config.a_base_addr),
        .col_id_base_addr_i  (accel_config.col_id_base_addr),
        .row_ptr_base_addr_i (accel_config.row_ptr_base_addr),
        .b_base_addr_i       (accel_config.b_base_addr),
        .c_base_addr_i       (accel_config.c_base_addr),

        .row_ptr_num_words_i (accel_config.row_ptr_num_words),
        .b_num_words_i       (accel_config.b_num_words),

        // TCDM interface
        .tcdm_master         (tcdm_master_raw),

        // Input buffer write ports
        .a_write_en_o        (a_write_en),
        .a_wdata_o           (a_wdata),

        .b_write_en_o        (b_write_en),
        .b_wdata_o           (b_wdata),

        .col_id_write_en_o   (col_id_write_en),
        .col_id_wdata_o      (col_id_wdata),

        .row_ptr_write_en_o  (row_ptr_write_en),
        .row_ptr_wdata_o     (row_ptr_wdata),

        // Output buffer read ports
        .c_read_row_addr_o   (c_read_row_addr),
        .c_read_word_addr_o  (c_read_word_addr),
        .c_rdata_i           (c_rdata),

        // Scheduler start / completion handshake
        .accel_start_o       (accel_start),
        .accel_done_i        (accel_done)
    );


    // ========================================================================
    // 12. A BUFFER
    // ========================================================================

    a_buffer #(
        .DATA_WIDTH      (DATA_WIDTH),
        .TOTAL_NNZ       (TOTAL_NNZ),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .USE_LATCHES     (USE_LATCHES)
    ) i_a_buffer (
        .clk_i       (clk_i),
        .rst_ni      (rst_ni),
        .clear_i     (target_clear),

        .write_en_i  (a_write_en),
        .wdata_i     (a_wdata),

        .read_addr_i (a_read_addr),
        .rdata_a_o   (a_data)
    );


    // ========================================================================
    // 13. B BUFFER
    // ========================================================================

    b_buffer #(
        .DATA_WIDTH      (DATA_WIDTH),
        .NUM_MACS        (NUM_MACS),
        .NUM_B_ROWS      (NUM_ROWS),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .USE_LATCHES     (USE_LATCHES)
    ) i_b_buffer (
        .clk_i           (clk_i),
        .rst_ni          (rst_ni),
        .clear_i         (target_clear),

        .write_en_i      (b_write_en),
        .wdata_i         (b_wdata),

        .read_row_addr_i (b_read_row_addr),
        .rdata_b_o       (b_data)
    );


    // ========================================================================
    // 14. COLUMN ID BUFFER
    // ========================================================================

    colID_buffer #(
        .DATA_WIDTH      (DATA_WIDTH),
        .TOTAL_ID        (TOTAL_NNZ),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .USE_LATCHES     (USE_LATCHES)
    ) i_colID_buffer (
        .clk_i       (clk_i),
        .rst_ni      (rst_ni),
        .clear_i     (target_clear),

        .write_en_i  (col_id_write_en),
        .wdata_i     (col_id_wdata),

        .read_addr_i (col_id_read_addr),
        .rdata_o     (col_id_data)
    );


    // ========================================================================
    // 15. ROW POINTER BUFFER
    // ========================================================================

    row_ptr_buffer #(
        .DATA_WIDTH      (DATA_WIDTH),
        .TOTAL_PTRS      (TOTAL_PTRS),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .USE_LATCHES     (USE_LATCHES)
    ) i_row_ptr_buffer (
        .clk_i          (clk_i),
        .rst_ni         (rst_ni),
        .clear_i        (target_clear),

        .write_en_i     (row_ptr_write_en),
        .wdata_i        (row_ptr_wdata),

        .read_row_idx_i (row_ptr_read_addr),

        .rdata_start_o  (row_ptr_start),
        .rdata_end_o    (row_ptr_end)
    );


    // ========================================================================
    // 16. C BUFFER
    // ========================================================================

    c_buffer #(
        .DATA_WIDTH_OUT  (DATA_WIDTH_OUT),
        .NUM_MACS        (NUM_MACS),
        .NUM_C_ROWS      (NUM_ROWS),
        .STREAM_WORD_BIT (STREAM_WORD_BIT),
        .USE_LATCHES     (USE_LATCHES)
    ) i_c_buffer (
        .clk_i             (clk_i),
        .rst_ni            (rst_ni),
        .clear_i           (target_clear),

        .write_en_i        (c_buf_write_en),
        .write_row_addr_i  (c_buf_write_row_addr),
        .wdata_i           (dp_data_out),

        .read_row_addr_i   (c_read_row_addr),
        .read_word_addr_i  (c_read_word_addr),
        .rdata_c_o         (c_rdata)
    );


    // ========================================================================
    // 17. SCHEDULER
    // ========================================================================

    scheduler #(
        .DATA_WIDTH     (DATA_WIDTH),
        .NUM_MACS       (NUM_MACS),
        .NUM_ROWS       (NUM_ROWS),
        .TOTAL_NNZ      (TOTAL_NNZ),
        .TOTAL_PTRS     (TOTAL_PTRS),
        .DATA_WIDTH_OUT (DATA_WIDTH_OUT)
    ) i_scheduler (

        .clk_i               (clk_i),
        .rst_ni              (rst_ni),
        .clear_i             (target_clear),

        // Start after streamer has loaded the input buffers
        .start_i             (accel_start),
        .done_o              (accel_done),

        .row_ptr_read_addr_o (row_ptr_read_addr),
        .row_ptr_start_i     (row_ptr_start),
        .row_ptr_end_i       (row_ptr_end),

        .col_id_read_addr_o  (col_id_read_addr),
        .col_id_i            (col_id_data),

        .a_read_addr_o       (a_read_addr),
        .b_read_row_addr_o   (b_read_row_addr),

        .c_write_en_o        (c_buf_write_en),
        .c_write_row_addr_o  (c_buf_write_row_addr),

        .dp_in_valid_o       (dp_in_valid),
        .dp_in_ready_i       (dp_in_ready),
        .dp_nnz_iterations_o (dp_nnz_iterations),

        .dp_out_valid_i      (dp_out_valid),
        .dp_out_ready_o      (dp_out_ready),

        .dp_matrix_end_i     (dp_matrix_end)
    );


    // ========================================================================
    // 18. DATAPATH
    // ========================================================================

    datapath #(
        .DATA_WIDTH     (DATA_WIDTH),
        .NUM_MACS       (NUM_MACS),
        .NUM_ROWS       (NUM_ROWS),
        .DATA_WIDTH_OUT (DATA_WIDTH_OUT)
    ) i_datapath (

        .clk_i            (clk_i),
        .rst_ni           (rst_ni),
        .clear_i          (target_clear),

        .nnz_iterations_i (dp_nnz_iterations),
        .matrix_end_o     (dp_matrix_end),

        .in_valid_i       (dp_in_valid),
        .in_ready_o       (dp_in_ready),

        .data_a_i         (a_data),
        .data_b_i         (b_data),

        .out_valid_o      (dp_out_valid),
        .out_ready_i      (dp_out_ready),

        .data_out_o       (dp_data_out)
    );


    // ========================================================================
    // 19. EVENT OUTPUT
    // ========================================================================

    // Event 0 is mapped by the cluster to event-unit ID 12.
    // The streamer completion is reported to the cluster.

    always_comb begin
        evt_o = '0;
        evt_o[0][0] = streamer_done;
    end

endmodule
